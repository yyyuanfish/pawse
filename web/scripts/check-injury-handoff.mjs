import assert from 'node:assert/strict';
import {hasVisibleInjury,injuryMessage} from '../src/agents/injuryHandoff.js';
import {liveSearchClinics} from '../src/agents/liveClinicSearch.js';
import {draftHandoff,generateSpeech} from '../src/agents/handoff.js';
assert.equal(hasVisibleInjury(null),false);
assert.equal(hasVisibleInjury({injury:{wound:'uncertain'}}),false);
const observation={injury:{wound:'suspected',blood_like_material:'uncertain',active_bleeding:'cannot_determine_from_photo'},limitations:['Still image only.']};
assert.equal(hasVisibleInjury(observation),true);
const requests=[];
globalThis.fetch=async(url,options)=>{
 const body=JSON.parse(options.body);requests.push({url,body,signal:options.signal});
 if(url.endsWith('/clinics/search'))return {ok:true,json:async()=>({clinics:[{id:'test',name:'Test practice',address:'Test address',source:'google_places',phone:'+41440000000',call_url:'tel:+41440000000',open_now:null}]})};
 if(url.endsWith('/voice/scripts'))return {ok:true,json:async()=>({lines:[{german:'Kann meine Katze untersucht werden?',subtitle:'Can my cat be examined?'}]})};
 return {ok:true,blob:async()=>new Blob(['test'],{type:'audio/wav'})};
};
await assert.rejects(liveSearchClinics(),/Location/);
assert.equal(requests.length,0);
const signal=new AbortController().signal;
const {clinics}=await liveSearchClinics({location:{lat:47.37,lng:8.54},signal});
assert.equal(requests[0].body.share_location,true);
assert.equal('share_with_ai' in requests[0].body,false);
assert.equal('query' in requests[0].body,false);
assert.equal(requests[0].signal,signal);
assert.equal(clinics[0].openUnknown,true);
const message=injuryMessage(observation,clinics[0],'Jumped today.');
assert.equal(JSON.parse(message).owner_report,'Jumped today.');
assert.match(message,/not a diagnosis/);
await assert.rejects(draftHandoff(message,'en','vet',false),/sharing/);
const script=await draftHandoff(message,'en','vet',true,signal);
assert.equal(requests[1].body.recipient,'vet');
assert.equal(requests[1].body.target_language,'de');
await assert.rejects(generateSpeech('text','my_voice',false),/sharing/);
await generateSpeech(script.lines[0].german,'my_voice',true,signal);
assert.equal(requests[2].body.voice,'my_voice');
assert.equal(requests[2].body.share_with_gradium,true);
assert.equal(requests.length,3);
globalThis.fetch=async()=>({ok:true,json:async()=>({clinics:[],warnings:['provider_not_configured']})});
await assert.rejects(liveSearchClinics({location:{lat:47,lng:8}}),/provider_not_configured/);
console.log('Injury → location → clinic → reviewed German own-voice contract passed (mock providers).');
